-- Moonlabs client portal schema for Cloudflare D1 (SQLite).
--
-- Access model (enforced in code by lib/portal/access.ts, there is no row-level security):
--   * Every client company is an `organization`. People belong to organizations through
--     `memberships` with role 'client' or 'admin'.
--   * `users.is_staff = 1` means Moonlabs staff: full access to every organization.
--   * Clients read their own organization's rows (never draft invoices) and create requests
--     and request comments as themselves. Everything else is written by org admins/staff.
--
-- Conventions: TEXT ids (crypto.randomUUID()), ISO-8601 UTC timestamps
-- (e.g. 2026-11-09T12:34:56.789Z), calendar dates as YYYY-MM-DD, booleans as 0/1.
-- No demo data here; see scripts/portal-seed-local.sql for local testing.

-- ---------------------------------------------------------------------------
-- People, organizations and sign-in
-- ---------------------------------------------------------------------------
CREATE TABLE organizations (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
  plan TEXT NOT NULL DEFAULT 'none' CHECK (plan IN ('none', 'crescent', 'half_moon', 'full_moon', 'custom')),
  plan_started_on TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND instr(email, '@') > 1),
  name TEXT CHECK (name IS NULL OR length(name) <= 120),
  -- pbkdf2$<iterations>$<salt b64>$<hash b64>; NULL for accounts that only use Google.
  password_hash TEXT,
  is_staff INTEGER NOT NULL DEFAULT 0 CHECK (is_staff IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE memberships (
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'client' CHECK (role IN ('client', 'admin')),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  PRIMARY KEY (user_id, org_id)
);
CREATE INDEX memberships_org_idx ON memberships (org_id);

-- Only the SHA-256 hash of the session token is stored; the token lives in an httpOnly cookie.
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  user_agent TEXT
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
CREATE INDEX sessions_expires_idx ON sessions (expires_at);

-- One-time invite links (/invite/<token>). org_id is NULL for a staff-only invite (first
-- admin bootstrap). is_staff = 1 makes the new account Moonlabs staff.
CREATE TABLE invites (
  id TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL CHECK (email = lower(email) AND instr(email, '@') > 1),
  org_id TEXT REFERENCES organizations (id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'client' CHECK (role IN ('client', 'admin')),
  is_staff INTEGER NOT NULL DEFAULT 0 CHECK (is_staff IN (0, 1)),
  expires_at TEXT NOT NULL,
  used_at TEXT,
  created_by TEXT REFERENCES users (id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  CHECK (org_id IS NOT NULL OR is_staff = 1)
);
CREATE INDEX invites_org_idx ON invites (org_id);
CREATE INDEX invites_email_idx ON invites (email);

-- One-time password reset links (/reset/<token>), generated by an admin.
CREATE TABLE password_resets (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL,
  used_at TEXT,
  created_by TEXT REFERENCES users (id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX password_resets_user_idx ON password_resets (user_id);

-- Failed password checks, for rate limiting (per email + IP, and per IP).
CREATE TABLE login_attempts (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  email TEXT NOT NULL,
  ip TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX login_attempts_email_ip_idx ON login_attempts (email, ip, created_at);
CREATE INDEX login_attempts_ip_idx ON login_attempts (ip, created_at);

-- ---------------------------------------------------------------------------
-- Projects
-- ---------------------------------------------------------------------------
CREATE TABLE projects (
  id TEXT PRIMARY KEY,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
  summary TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'on_hold', 'completed', 'cancelled')),
  started_on TEXT,
  target_on TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX projects_org_idx ON projects (org_id);

-- One row per stage per project (Audit -> Design -> Build -> Test -> Live).
CREATE TABLE project_stages (
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  stage TEXT NOT NULL CHECK (stage IN ('audit', 'design', 'build', 'test', 'live')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'done')),
  started_on TEXT,
  due_on TEXT,
  completed_on TEXT,
  notes TEXT,
  UNIQUE (project_id, stage)
);
CREATE INDEX project_stages_org_idx ON project_stages (org_id);

CREATE TABLE project_milestones (
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  stage TEXT CHECK (stage IS NULL OR stage IN ('audit', 'design', 'build', 'test', 'live')),
  title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  done INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0, 1)),
  due_on TEXT,
  position INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX project_milestones_project_idx ON project_milestones (project_id);
CREATE INDEX project_milestones_org_idx ON project_milestones (org_id);

CREATE TABLE project_updates (
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  author_id TEXT REFERENCES users (id) ON DELETE SET NULL,
  title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  body TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX project_updates_org_idx ON project_updates (org_id, created_at);
CREATE INDEX project_updates_project_idx ON project_updates (project_id, created_at);

-- ---------------------------------------------------------------------------
-- Automations
-- ---------------------------------------------------------------------------
CREATE TABLE automations (
  id TEXT PRIMARY KEY,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  project_id TEXT REFERENCES projects (id) ON DELETE SET NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
  description TEXT,
  trigger_label TEXT,
  status TEXT NOT NULL DEFAULT 'healthy' CHECK (status IN ('healthy', 'warning', 'failing', 'paused')),
  minutes_saved_per_run INTEGER NOT NULL DEFAULT 0 CHECK (minutes_saved_per_run >= 0),
  last_run_at TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX automations_org_idx ON automations (org_id);
CREATE INDEX automations_project_idx ON automations (project_id);

CREATE TABLE automation_runs (
  id TEXT PRIMARY KEY,
  automation_id TEXT NOT NULL REFERENCES automations (id) ON DELETE CASCADE,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('success', 'failed', 'running')),
  started_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  duration_ms INTEGER CHECK (duration_ms IS NULL OR duration_ms >= 0),
  items_processed INTEGER CHECK (items_processed IS NULL OR items_processed >= 0),
  minutes_saved INTEGER NOT NULL DEFAULT 0 CHECK (minutes_saved >= 0),
  message TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX automation_runs_org_started_idx ON automation_runs (org_id, started_at);
CREATE INDEX automation_runs_automation_idx ON automation_runs (automation_id, started_at);

-- Keep automations.last_run_at current when runs are logged.
CREATE TRIGGER automation_runs_touch AFTER INSERT ON automation_runs
BEGIN
  UPDATE automations
     SET last_run_at = CASE
       WHEN last_run_at IS NULL OR last_run_at < NEW.started_at THEN NEW.started_at
       ELSE last_run_at END
   WHERE id = NEW.automation_id;
END;

-- ---------------------------------------------------------------------------
-- Requests
-- ---------------------------------------------------------------------------
CREATE TABLE requests (
  id TEXT PRIMARY KEY,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  project_id TEXT REFERENCES projects (id) ON DELETE SET NULL,
  created_by TEXT REFERENCES users (id) ON DELETE SET NULL,
  title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  description TEXT CHECK (description IS NULL OR length(description) <= 10000),
  priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_progress', 'waiting', 'resolved', 'closed')),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX requests_org_idx ON requests (org_id, updated_at);
CREATE INDEX requests_project_idx ON requests (project_id);

CREATE TABLE request_comments (
  id TEXT PRIMARY KEY,
  request_id TEXT NOT NULL REFERENCES requests (id) ON DELETE CASCADE,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  author_id TEXT REFERENCES users (id) ON DELETE SET NULL,
  body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 10000),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX request_comments_request_idx ON request_comments (request_id, created_at);
CREATE INDEX request_comments_org_idx ON request_comments (org_id, created_at);

-- Bump requests.updated_at on every new comment.
CREATE TRIGGER request_comments_touch AFTER INSERT ON request_comments
BEGIN
  UPDATE requests SET updated_at = NEW.created_at WHERE id = NEW.request_id;
END;

-- ---------------------------------------------------------------------------
-- Files and invoices
-- ---------------------------------------------------------------------------
-- A deliverable is either an object in the FILES R2 bucket (r2_key) or a link (external_url).
CREATE TABLE files (
  id TEXT PRIMARY KEY,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  project_id TEXT REFERENCES projects (id) ON DELETE SET NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 255),
  r2_key TEXT UNIQUE,
  external_url TEXT CHECK (external_url IS NULL OR external_url LIKE 'https://%'),
  size_bytes INTEGER CHECK (size_bytes IS NULL OR size_bytes >= 0),
  content_type TEXT,
  uploaded_by TEXT REFERENCES users (id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  CHECK ((r2_key IS NULL) <> (external_url IS NULL))
);
CREATE INDEX files_org_idx ON files (org_id, created_at);
CREATE INDEX files_project_idx ON files (project_id);

CREATE TABLE invoices (
  id TEXT PRIMARY KEY,
  org_id TEXT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  number TEXT NOT NULL CHECK (length(number) BETWEEN 1 AND 40),
  issued_on TEXT NOT NULL,
  due_on TEXT,
  amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (length(currency) = 3),
  -- Clients never see 'draft' invoices.
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('draft', 'open', 'paid', 'overdue', 'void')),
  url TEXT CHECK (url IS NULL OR url LIKE 'https://%' OR url LIKE 'http://%'),
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  UNIQUE (org_id, number)
);
CREATE INDEX invoices_org_idx ON invoices (org_id, issued_on);

-- updated_at on edits (recursive triggers are off in SQLite, so this does not loop).
CREATE TRIGGER projects_updated_at AFTER UPDATE ON projects
WHEN NEW.updated_at = OLD.updated_at
BEGIN
  UPDATE projects SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = NEW.id;
END;

CREATE TRIGGER requests_updated_at AFTER UPDATE ON requests
WHEN NEW.updated_at = OLD.updated_at
BEGIN
  UPDATE requests SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = NEW.id;
END;
